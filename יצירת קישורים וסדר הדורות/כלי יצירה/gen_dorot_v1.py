def era(parts,title,fn):
    k=norm(title)
    if k in up: return up[k],'רשמי'
    if parts and parts[0].startswith('ספרים חדשים'):
        key=parts[1] if len(parts)>1 else fn
        if key in NEW: return NEW[key],'ידני'
        return None,''
    for t in (title,):
        for s,e in SPEC.items():
            if norm(s)==norm(t): return e,'ידני'
    if parts[:1]==['מדרש']: return H,'תיקייה'
    if 'מחברי זמננו' in parts or parts[:1]==['ספרים - ריבית']: return M,'תיקייה'
    if 'אחרונים' in parts: return A,'תיקייה'
    if 'ראשונים' in parts or 'גאונים' in parts:
        return (R,'תיקייה')
    if parts[:1]==['תנ״ך']:
        if "כתאב אלתאג" in title: return R,'תיקייה'
        if len(parts)>1 and parts[1] in('תורה','נביאים','כתובים'): return T,'תיקייה'
        if len(parts)>1 and parts[1] in('תרגומים','מסורה'): return H,'תיקייה'
    if parts[:1]==['תלמוד בבלי'] and 'שס וגשל' in parts: return H,'תיקייה'
    if parts[:1]==['משנה']: return M,'תיקייה'
    if 'מילונים וספרי יעץ' in parts[:1]: return M,'תיקייה'
    if 'משנה תורה' in parts or 'ספרי מצוות' in parts: return R,'תיקייה'
    if 'שולחן ערוך' in parts or 'שו״ע' in parts: return A,'תיקייה'
    return None,''
